def _residual_phase(grid: dict) -> np.ndarray:
    """Known smooth angular aberration used only as synthetic ground truth."""
    X = np.asarray(grid["X"], float)
    Y = np.asarray(grid["Y"], float)
    R = np.hypot(X, Y)
    TH = np.arctan2(Y, X)
    # Angular terms are intentionally modest: the physical parameter fit must
    # still have enough information to identify the geometric/amplitude errors.
    phase = 0.42*np.cos(2.0*TH) + 0.24*np.sin(3.0*TH) + 0.12*np.cos(5.0*TH)
    # Suppress the undefined angular coordinate in an optically irrelevant tiny
    # disk without changing the sampled Miao annuli.
    phase *= 1.0 - np.exp(-(R/90e-6)**2)
    return np.asarray(phase, float)


def _post_axicon_with_phase(route: dict, correction_phase_rad: np.ndarray | None) -> np.ndarray:
    if correction_phase_rad is None:
        return np.asarray(route["post_axicon"], np.complex128)
    tx, ty = map(float, route["metadata"]["axicon_rigid_tilt_rad"])
    if tx != 0.0 or ty != 0.0:
        raise ValueError("benchmark correction application assumes an untilted axicon plane")
    inc = np.asarray(route["field_on_axicon_plane"], np.complex128)
    local = np.asarray(route["post_axicon_local"], np.complex128)
    denom = np.where(np.abs(inc) > 1e-12, inc, 1.0 + 0j)
    transmission = local / denom
    transmission = np.where(np.abs(inc) > 1e-12, transmission, 1.0 + 0j)
    phase = np.asarray(correction_phase_rad, float)
    if phase.shape != inc.shape:
        raise ValueError("correction map does not match optical simulation grid")
    return np.asarray(inc*np.exp(1j*phase)*transmission, np.complex128)


def _propagate(route: dict, z_m: np.ndarray, correction_phase_rad: np.ndarray | None = None) -> np.ndarray:
    field0 = _post_axicon_with_phase(route, correction_phase_rad)
    prop = build_fixed_support_spectrum(
        field0,
        dict(route["grid"]),
        wavelength_m=float(route["metadata"]["wavelength_m"]),
        z_max_m=float(np.max(z_m)),
        minimum_retained_spectral_power=0.995,
    )
    return np.asarray([
        np.abs(np.asarray(native_field_at_z(prop, float(z)), np.complex128))**2
        for z in np.asarray(z_m, float)
    ], float)


def _add_noise(stack: np.ndarray, standard_normal: np.ndarray) -> np.ndarray:
    a = np.asarray(stack, float)
    peak = np.max(a, axis=(1, 2), keepdims=True)
    return np.maximum(a + NOISE_SIGMA*peak*np.asarray(standard_normal, float), 0.0)


class PhysicalSimulator:
    """Forward model used by the physical-parameter estimation stage."""
    def __init__(self, crop_ids: np.ndarray):
        self.crop_ids = np.asarray(crop_ids, int)
        self.cache: dict[SystemErrorConfig, np.ndarray] = {}

    def __call__(self, config: SystemErrorConfig) -> np.ndarray:
        if config not in self.cache:
            r = _route(config, None)
            stack = _propagate(r, Z_FIT_M)
            ids = self.crop_ids
            self.cache[config] = np.asarray(stack[:, ids[:, None], ids], float)
        return self.cache[config]


def _compensate_physical_parameters(
    actual: SystemErrorConfig,
    estimated: SystemErrorConfig,
) -> SystemErrorConfig:
    """Apply model-derived alignment/scale updates to the synthetic system.

    Only parameters admitted to FIT_PARAMETERS are changed.  Subtraction is used
    for offsets and division for scale factors, so an imperfect estimate leaves
    the corresponding residual error rather than silently replacing the truth.
    """
    ax, ay = actual.beam.decentre_m
    ex, ey = estimated.beam.decentre_m
    beam = replace(
        actual.beam,
        decentre_m=(float(ax-ex), float(ay-ey)),
        radius_x_scale=float(actual.beam.radius_x_scale)/max(float(estimated.beam.radius_x_scale), EPS),
        radius_y_scale=float(actual.beam.radius_y_scale)/max(float(estimated.beam.radius_y_scale), EPS),
    )

    aox, aoy = actual.slm1.pattern_offset_m
    eox, eoy = estimated.slm1.pattern_offset_m
    slm1 = replace(actual.slm1, pattern_offset_m=(float(aox-eox), float(aoy-eoy)))

    aix, aiy = actual.fourf.iris_offset_m
    eix, eiy = estimated.fourf.iris_offset_m
    fourf = replace(
        actual.fourf,
        iris_offset_m=(float(aix-eix), float(aiy-eiy)),
        iris_radius_scale=float(actual.fourf.iris_radius_scale)/max(float(estimated.fourf.iris_radius_scale), EPS),
    )

    adx, ady = actual.axicon.decentre_m
    edx, edy = estimated.axicon.decentre_m
    axicon = replace(actual.axicon, decentre_m=(float(adx-edx), float(ady-edy)))
    return replace(actual, beam=beam, slm1=slm1, fourf=fourf, axicon=axicon)


def _reference_rows(route: dict, retrievals: list, z_abs_m: np.ndarray) -> np.ndarray:
    """Independent input-intensity reference used only to resolve the conjugate branch."""
    field = np.asarray(route["field_on_axicon_plane"], np.complex128)
    intensity = np.abs(field)**2
    x = np.asarray(route["grid"]["x"], float)
    dx = float(route["grid"]["dx"])
    wavelength = float(route["metadata"]["wavelength_m"])
    k = 2*np.pi/wavelength
    kp = np.asarray([r.k_perp_m_inv for r in retrievals], float)
    rho = np.asarray(z_abs_m, float)*kp/k
    theta = np.asarray(retrievals[0].theta_rad, float)
    rows = []
    for rr in rho:
        xs = rr*np.cos(theta)
        ys = rr*np.sin(theta)
        xc = (xs-x[0])/dx
        yc = (ys-x[0])/dx
        rows.append(ndimage.map_coordinates(intensity, [yc, xc], order=1,
                                             mode="constant", cval=0.0))
    rows = np.asarray(rows, float)
    return rows[np.argsort(rho)]


def _map_cartesian_phase_to_grid(cart: dict, grid: dict) -> tuple[np.ndarray, np.ndarray]:
    phase = np.asarray(cart["conjugate_correction_phase_rad"], float)
    axis = np.asarray(cart["x_m"], float)
    unit = np.zeros_like(phase, np.complex128)
    valid = np.isfinite(phase)
    unit[valid] = np.exp(1j*phase[valid])
    X = np.asarray(grid["X"], float)
    Y = np.asarray(grid["Y"], float)
    step = float(axis[1]-axis[0])
    xc = (X-axis[0])/step
    yc = (Y-axis[0])/step
    real = ndimage.map_coordinates(unit.real, [yc, xc], order=1, mode="constant", cval=0.0)
    imag = ndimage.map_coordinates(unit.imag, [yc, xc], order=1, mode="constant", cval=0.0)
    mag = np.hypot(real, imag)
    out = np.zeros_like(X, float)
    ok = mag > 0.25
    out[ok] = np.angle(real[ok] + 1j*imag[ok])
    return out, ok


def _miao_correction(route: dict, noisy_stack: np.ndarray) -> tuple[np.ndarray, dict]:
    grid = route["grid"]
    pixel = float(grid["dx"])
    nominal_kp = float(route["metadata"]["axicon"]["exact_kr_m_inv"])
    retrievals = []
    for i, (image, z) in enumerate(zip(np.asarray(noisy_stack, float), Z_FIT_M)):
        cy, cx, _ = find_dark_core_center(image)
        retrievals.append(fit_plane_adaptive(
            image,
            i,
            float(z),
            (float(cy), float(cx)),
            pixel,
            Q,
            nominal_kp,
            max_aberration_order=10,
            order_step=2,
            cost_threshold=0.045,
            min_fractional_improvement=0.008,
            rmax_um=620,
            n_r=34,
            n_theta=72,
        ))
    refs = _reference_rows(route, retrievals, Z_FIT_M)
    full = assemble_full_aperture(
        retrievals,
        Z_FIT_M,
        float(route["metadata"]["wavelength_m"]),
        k_perp_nominal_m_inv=nominal_kp,
        reference_intensity_rows=refs,
    )
    cart = interpolate_to_cartesian(full, grid_size=512, padding_fraction=0.03)
    correction, valid = _map_cartesian_phase_to_grid(cart, grid)
    diag = {
        "branch": full.branch,
        "branch_score_direct": full.branch_score_direct,
        "branch_score_conjugate": full.branch_score_conjugate,
        "valid_grid_fraction": float(np.mean(valid)),
        "median_plane_fit_corr": float(np.median([r.fit_corr for r in retrievals])),
        "median_plane_fit_nrmse": float(np.median([r.fit_nrmse for r in retrievals])),
        "median_k_perp_m_inv": float(np.median([r.k_perp_m_inv for r in retrievals])),
    }
    return correction, diag


def _metric_rows(
    z_m: np.ndarray,
    ideal: np.ndarray,
    distorted: np.ndarray,
    miao: np.ndarray,
    hybrid: np.ndarray,
    grid: dict,
) -> pd.DataFrame:
    X = np.asarray(grid["X"], float)
    Y = np.asarray(grid["Y"], float)
    roi = np.hypot(X, Y) <= METRIC_RADIUS_M

    def metrics(a: np.ndarray, b: np.ndarray) -> tuple[float, float]:
        av = np.asarray(a, float)[roi]
        bv = np.asarray(b, float)[roi]
        av = av/max(float(np.max(av)), EPS)
        bv = bv/max(float(np.max(bv)), EPS)
        corr = float(np.corrcoef(av, bv)[0, 1])
        rmse = float(np.sqrt(np.mean((av-bv)**2)))
        return corr, rmse

    rows = []
    for i, z in enumerate(np.asarray(z_m, float)):
        row = {"z_mm": float(z*1e3)}
        for key, stack in (("distorted", distorted), ("miao_only", miao), ("digital_twin_plus_miao", hybrid)):
            corr, rmse = metrics(stack[i], ideal[i])
            row[f"{key}_pearson_r"] = corr
            row[f"{key}_nrmse"] = rmse
        rows.append(row)
    return pd.DataFrame(rows)


def _xz(stack: np.ndarray, grid: dict) -> np.ndarray:
    a = plane_normalise_stack(stack)
    x = np.asarray(grid["x"], float)
    iy = int(np.argmin(np.abs(x)))
    return np.asarray(a[:, iy, :], float).T


def _xcut(stack: np.ndarray, grid: dict, iz: int) -> tuple[np.ndarray, np.ndarray]:
    a = np.asarray(stack[iz], float)
    x = np.asarray(grid["x"], float)
    iy = int(np.argmin(np.abs(x)))
    cut = a[iy, :]
    return x*1e3, cut/max(float(np.max(cut)), EPS)


