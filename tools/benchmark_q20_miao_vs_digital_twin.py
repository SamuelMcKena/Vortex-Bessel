def _format_physical_fit(fit) -> tuple[list[str], dict[str, float]]:
    values: dict[str, float] = {}
    labels = []
    for step in fit.steps:
        if not step.accepted or step.selected_family is None or step.selected_value is None:
            continue
        values[step.selected_family] = float(step.selected_value)
        if step.selected_family == "axicon_lateral_decentre_x":
            labels.append(f"axicon position  {step.selected_value*1e6:+.0f} µm")
        elif step.selected_family == "beam_radius_scale":
            labels.append(f"input beam radius  {step.selected_value:.2f} × nominal")
        elif step.selected_family == "beam_lateral_decentre_x":
            labels.append(f"beam position  {step.selected_value*1e6:+.0f} µm")
        elif step.selected_family == "slm1_hologram_offset_x":
            labels.append(f"SLM1 pattern position  {step.selected_value*1e6:+.0f} µm")
        elif step.selected_family == "fourf_iris_offset_x":
            labels.append(f"Fourier iris position  {step.selected_value*1e3:+.2f} mm")
        elif step.selected_family == "fourf_iris_radius_scale":
            labels.append(f"Fourier iris radius  {step.selected_value:.2f} × nominal")
        else:
            labels.append(f"{step.selected_family}: {step.selected_value:g}")
    return labels, values


