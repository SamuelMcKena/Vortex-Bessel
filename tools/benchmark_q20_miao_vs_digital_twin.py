"""Controlled q=20 comparison: Miao-style phase retrieval alone versus
physical-system estimation followed by the same phase retrieval.

The purpose of this benchmark is deliberately narrow and falsifiable.  A
synthetic q=20 beam is generated by the same Gaussian -> SLM1 -> SLM2 ->
explicit 4F/iris -> axicon route used for the system-sensitivity calculations.
Two known physical perturbations and a known non-axisymmetric phase aberration
are introduced.  The same noisy intensity z-stack is then treated in two ways:

A) Miao-style intensity-only residual-phase retrieval applied directly.
B) Estimate physical system parameters from the z-stack, apply the inferred
   alignment update in the digital twin, then run the same Miao retrieval on
   the remaining wavefront.

Both retrieved phase maps are applied once on the axicon-input plane and are
propagated through the actual simulated axicon.  Corrected fields are therefore
single-mask propagation predictions, not stitched per-plane corrected images.
The comparison is against the independently generated nominal q=20 route.

This is a synthetic method-comparison study.  It is not an experimental claim.
"""
