def build(out: Path = OUT) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    registry = system_sweep_registry()

    nominal_config = SystemErrorConfig()
    nominal_route_no_phase = _route(nominal_config, None)
    residual_phase = _residual_phase(nominal_route_no_phase["grid"])

    truth_config = apply_registry_family(nominal_config, "beam_radius_scale", 0.85, registry=registry)
    truth_config = apply_registry_family(truth_config, "axicon_lateral_decentre_x", 250e-6, registry=registry)

    ideal_route = _route(nominal_config, None)
    distorted_route = _route(truth_config, residual_phase)
    ideal_fit = _propagate(ideal_route, Z_FIT_M)
    distorted_fit_clean = _propagate(distorted_route, Z_FIT_M)

    rng = np.random.default_rng(SEED)
    noise = rng.normal(size=distorted_fit_clean.shape)
    distorted_fit = _add_noise(distorted_fit_clean, noise)

    x = np.asarray(ideal_route["grid"]["x"], float)
    ids = np.flatnonzero(np.abs(x) <= FIT_CROP_HALF_M)
    target_crop = distorted_fit[:, ids[:, None], ids]
    simulator = PhysicalSimulator(ids)

    physical_fit = hierarchical_physical_fit(
        target_stack=target_crop,
        simulate_config=simulator,
        families=FIT_PARAMETERS,
        registry=registry,
        max_stages=2,
        min_improvement_fraction=0.003,
    )
    compensated_config = _compensate_physical_parameters(truth_config, physical_fit.final_config)
    compensated_route = _route(compensated_config, residual_phase)
    compensated_fit_clean = _propagate(compensated_route, Z_FIT_M)
    compensated_fit = _add_noise(compensated_fit_clean, noise)

    # Baseline paper-style retrieval and digital-twin-assisted retrieval use the
    # same Miao implementation and the same noise realization.
    miao_phase, miao_diag = _miao_correction(distorted_route, distorted_fit)
    hybrid_phase, hybrid_diag = _miao_correction(compensated_route, compensated_fit)

    ideal_display = _propagate(ideal_route, Z_DISPLAY_M)
    distorted_display = _propagate(distorted_route, Z_DISPLAY_M)
    miao_display = _propagate(distorted_route, Z_DISPLAY_M, miao_phase)
    hybrid_display = _propagate(compensated_route, Z_DISPLAY_M, hybrid_phase)

    metrics = _metric_rows(
        Z_DISPLAY_M,
        ideal_display,
        distorted_display,
        miao_display,
        hybrid_display,
        ideal_route["grid"],
    )
    metrics.to_csv(out/"comparison_metrics_vs_z.csv", index=False)

    fit_labels, recovered = _format_physical_fit(physical_fit)
    summary = {
        "study": "Miao-style q20 phase retrieval versus digital-twin parameter estimation plus the same Miao retrieval",
        "interpretation": "synthetic controlled method comparison; corrected stacks are single retrieved phase maps propagated through the simulated axicon",
        "q": Q,
        "truth": {
            "beam_radius_scale": 0.85,
            "axicon_lateral_decentre_x_m": 250e-6,
            "residual_phase": "0.42 cos(2theta) + 0.24 sin(3theta) + 0.12 cos(5theta), smoothly suppressed inside r=90 um",
        },
        "noise_sigma_fraction_of_plane_peak": NOISE_SIGMA,
        "fit_z_planes": int(len(Z_FIT_M)),
        "evaluation_z_planes": int(len(Z_DISPLAY_M)),
        "physical_parameter_estimation": {
            "candidate_parameters": list(FIT_PARAMETERS),
            "selected": recovered,
            "selected_display": fit_labels,
            "mean_transverse_error_definition": "mean over z of pixel RMSE between independently peak-normalized model and data planes on fixed lab coordinates",
            "E_I_before": float(physical_fit.initial_cost),
            "E_I_after": float(physical_fit.final_cost),
            "trace": physical_fit.as_dict(),
        },
        "miao_only": {
            **miao_diag,
            "mean_pearson_r": float(metrics.miao_only_pearson_r.mean()),
            "median_pearson_r": float(metrics.miao_only_pearson_r.median()),
            "mean_nrmse": float(metrics.miao_only_nrmse.mean()),
            "median_nrmse": float(metrics.miao_only_nrmse.median()),
        },
        "digital_twin_plus_miao": {
            **hybrid_diag,
            "mean_pearson_r": float(metrics.digital_twin_plus_miao_pearson_r.mean()),
            "median_pearson_r": float(metrics.digital_twin_plus_miao_pearson_r.median()),
            "mean_nrmse": float(metrics.digital_twin_plus_miao_nrmse.mean()),
            "median_nrmse": float(metrics.digital_twin_plus_miao_nrmse.median()),
        },
        "aberrated": {
            "mean_pearson_r": float(metrics.distorted_pearson_r.mean()),
            "mean_nrmse": float(metrics.distorted_nrmse.mean()),
        },
    }
    summary["difference_hybrid_minus_miao"] = {
        "mean_pearson_r": float(summary["digital_twin_plus_miao"]["mean_pearson_r"] - summary["miao_only"]["mean_pearson_r"]),
        "mean_nrmse": float(summary["digital_twin_plus_miao"]["mean_nrmse"] - summary["miao_only"]["mean_nrmse"]),
    }

    np.save(out/"miao_only_correction_phase_on_axicon_input_rad.npy", miao_phase.astype(np.float32))
    np.save(out/"digital_twin_plus_miao_correction_phase_on_axicon_input_rad.npy", hybrid_phase.astype(np.float32))
    np.save(out/"synthetic_residual_phase_truth_on_slm1_rad.npy", residual_phase.astype(np.float32))

    png, pdf, preview = _build_figure(
        out,
        ideal_route["grid"],
        physical_fit,
        metrics,
        ideal_display,
        distorted_display,
        miao_display,
        hybrid_display,
        summary,
    )
    with Image.open(png) as im:
        summary["assets"] = {
            "png_500dpi": str(png),
            "pdf": str(pdf),
            "preview": str(preview),
            "png_pixel_size": list(im.size),
            "png_dpi": list(im.info.get("dpi", (0, 0))),
            "metrics_csv": str(out/"comparison_metrics_vs_z.csv"),
        }
    (out/"summary.json").write_text(json.dumps(summary, indent=2)+"\n", encoding="utf-8")
    print(json.dumps(summary, indent=2))
    return summary


if __name__ == "__main__":
    build()
