def write_registry_outputs(output_dir: str | Path) -> dict[str, Path]:
    """Write the registry and visual QA CSVs to ``output_dir``."""

    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    registry_path = out / "figure_output_registry.csv"
    visual_path = out / "figure_visual_quality_audit.csv"
    registry_frame().to_csv(registry_path, index=False)
    visual_quality_frame().to_csv(visual_path, index=False)
    return {"registry": registry_path, "visual_quality": visual_path}


def validate_registry(items: Iterable[FigureRegistryItem] | None = None) -> list[str]:
    """Return human-readable validation errors for registry consistency."""

    errors: list[str] = []
    selected = tuple(registry_items() if items is None else items)
    for item in selected:
        if item.status not in STATUS_VALUES:
            errors.append(f"{item.output_path}: invalid status {item.status!r}")
        if item.status == "legacy_quarantined" and item.final_export_allowed:
            errors.append(f"{item.output_path}: legacy item cannot be final_export_allowed")
        if item.final_export_allowed:
            if not item.stage or item.stage == "unknown":
                errors.append(f"{item.output_path}: final-export item missing stage")
            if not item.caption_gate_key:
                errors.append(f"{item.output_path}: final-export item missing caption gate")
            if item.visual_quality_status in {"legacy_not_reviewed", "rejected"}:
                errors.append(f"{item.output_path}: final-export item has unsafe visual quality status")
            gate = caption_gate(item.caption_gate_key)
            if item.caveat_required and not gate.caveat_text:
                errors.append(f"{item.output_path}: required caveat is empty")
    return errors


