FIGURE_REGISTRY_SCHEMA_VERSION = "1.0.0"

STATUS_VALUES = {
    "final_export_allowed",
    "diagnostic_allowed",
    "exploratory_only",
    "legacy_quarantined",
    "rejected",
}

VISUAL_QUALITY_STATUS = {
    "table_or_metadata",
    "caption_gated",
    "diagnostic_only",
    "needs_regeneration",
    "legacy_not_reviewed",
    "rejected",
}

PIXELATION_STATUS = {
    "not_applicable",
    "acceptable",
    "review_at_manuscript_size",
    "dense_or_compressed",
    "unknown",
}


class PublicationExportGateError(ValueError):
    """Raised when export code attempts to use a blocked output."""


@dataclass(frozen=True)
class FigureRegistryItem:
    """One governed output family.

    ``output_path`` may be a concrete path or a fnmatch-style path pattern.
    """

    output_path: str
    stage: str
    notebook_source: str
    source_csv: str
    source_run_id: str
    source_schema_version: str
    status: str
    reason: str
    caveat_required: bool
    model_level: str
    hardware_status: str
    material_model_status: str
    propagation_power_label: str
    visual_quality_status: str
    pixelation_status: str
    final_export_allowed: bool
    visualisation_type: str
    caption_gate_key: str
    recommended_action: str
    interpolation_used: str = "unknown"
    interpolation_label_present: str = "unknown"
    units_present: str = "unknown"
    colourbar_label_present: str = "unknown"
    qa_label_visible: str = "unknown"

    def __post_init__(self) -> None:
        if self.status not in STATUS_VALUES:
            raise ValueError(f"Invalid registry status: {self.status!r}")
        if self.visual_quality_status not in VISUAL_QUALITY_STATUS:
            raise ValueError(f"Invalid visual_quality_status: {self.visual_quality_status!r}")
        if self.pixelation_status not in PIXELATION_STATUS:
            raise ValueError(f"Invalid pixelation_status: {self.pixelation_status!r}")
        if bool(self.final_export_allowed) != (self.status == "final_export_allowed"):
            raise ValueError("final_export_allowed must match status == 'final_export_allowed'.")


def _item(
    output_path: str,
    stage: str,
    notebook_source: str,
    source_csv: str,
    status: str,
    reason: str,
    caption_gate_key: str,
    *,
    source_schema_version: str = "unknown",
    source_run_id: str = "unknown",
    caveat_required: bool = True,
    model_level: str = "not_applicable",
    hardware_status: str = "not_applicable",
    material_model_status: str = "not_applicable",
    propagation_power_label: str = "not_applicable",
    visual_quality_status: str = "caption_gated",
    pixelation_status: str = "review_at_manuscript_size",
    visualisation_type: str = "output_family",
    recommended_action: str = "Use registry gate before export.",
    interpolation_used: str = "unknown",
    interpolation_label_present: str = "unknown",
    units_present: str = "unknown",
    colourbar_label_present: str = "unknown",
    qa_label_visible: str = "unknown",
) -> FigureRegistryItem:
    return FigureRegistryItem(
        output_path=output_path,
        stage=stage,
        notebook_source=notebook_source,
        source_csv=source_csv,
        source_run_id=source_run_id,
        source_schema_version=source_schema_version,
        status=status,
        reason=reason,
        caveat_required=bool(caveat_required),
        model_level=model_level,
        hardware_status=hardware_status,
        material_model_status=material_model_status,
        propagation_power_label=propagation_power_label,
        visual_quality_status=visual_quality_status,
        pixelation_status=pixelation_status,
        final_export_allowed=status == "final_export_allowed",
        visualisation_type=visualisation_type,
        caption_gate_key=caption_gate_key,
        recommended_action=recommended_action,
        interpolation_used=interpolation_used,
        interpolation_label_present=interpolation_label_present,
        units_present=units_present,
        colourbar_label_present=colourbar_label_present,
        qa_label_visible=qa_label_visible,
    )


