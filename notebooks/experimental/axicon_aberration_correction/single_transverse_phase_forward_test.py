"""Single-transverse-phase forward test for the q=20 Bessel retrieval.

This is the authoritative forward-model closure test for the presentation path.
It deliberately does not consume the legacy normalized z-order-to-radius map.

The measured z-stack is first used to retrieve one residual angular phase per
sampled input annulus.  Those rows are mapped to a *single transverse input-plane
phase* via rho_z = z tan(alpha).  That phase is then used in one common
band-limited angular-spectrum propagation model:

    ideal input
    ideal input * exp(+i psi_residual)       -> predicted measured distortion
    ideal input * exp(+i psi_residual) * exp(-i psi_residual)
                                             -> model correction closure

There is no independent longitudinal correction phase.  All z-dependence in the
predicted fields is generated by propagation.
"""
