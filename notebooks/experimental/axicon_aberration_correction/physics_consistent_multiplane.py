"""Physics-consistent multi-plane wavefront retrieval for the q=20 z-scan.

This module replaces the original notebook's "recover a phase at z0, fit it,
then propagate with absolute z labels" diagnostic.  It enforces one central
physical rule:

    all measured planes must be generated by propagation of ONE complex field
    at ONE reference plane.

The measured z-stack therefore constrains the longitudinal evolution of the
wavefront without inventing an independently adjustable phase for every z.
A phase correction remains a two-dimensional phase function at the plane where
it is applied; the corresponding x-y-z field is produced by wave propagation.

The module deliberately distinguishes:
  * total reconstructed phase,
  * nominal model phase,
  * residual phase = angle(U_retrieved * conj(U_nominal)), and
  * a virtual correction at the camera/reference plane.

The virtual correction is a diagnostic only.  It is NOT an SLM2 command until
the camera-to-SLM optical transform, magnification, parity/rotation, illuminated
footprint and phase LUT are calibrated.
"""
